#!/usr/bin/env python3
"""Generate per-PR tasks/pr_<n>/workload/ scaffolds from clusters.json + workloads.json.

Each workload/ dir gets, idempotently:
  Dockerfile        - isolated image for THIS PR's workload (cpu or gpu base)
  run_workload.sh   - runs the author-mimicking workload for base + gold arms,
                      prints parseable lines, exits 0 even if an arm skips
  download.sh       - fetch-on-demand, gated; fetches shared weights into
                      ../../../.weights/<cluster> ONLY when run; nothing now
  meta.json         - the resolved {needs, cluster, model, cmd, script} for run.sh

Re-runnable: overwrites the three generated files, never touches bench.py/problem.md.
"""
import json
import os
import stat

HERE = os.path.dirname(os.path.abspath(__file__))
CLUSTERS = json.load(open(os.path.join(HERE, "clusters.json")))
WORK = json.load(open(os.path.join(HERE, "workloads.json")))

# invert: pr -> cluster key (a pr may appear in >1 cluster; keep ALL, cmd picks)
PR_CLUSTERS = {}
for ck, c in CLUSTERS["clusters"].items():
    for pr in c["prs"]:
        PR_CLUSTERS.setdefault(str(pr), []).append(ck)


def chmod_x(path):
    os.chmod(path, os.stat(path).st_mode | stat.S_IEXEC | stat.S_IXGRP | stat.S_IXOTH)


# ---- the CPU base image (no model): python:3.12-slim + CPU torch + import deps ----
CPU_DEPS = (
    "numpy pydantic psutil tabulate cloudpickle msgspec typing_extensions "
    "transformers regex filelock huggingface_hub cachetools pillow py-cpuinfo "
    "cbor2 pyzmq blake3 pybase64 prometheus_client fastapi openai aiohttp "
    "requests diskcache numba"
)

CPU_DOCKERFILE = """# AUTO-GENERATED by gen_workloads.py — PR #{pr} ({title})
# Isolated CPU workload image. vLLM source is NOT installed; the base_sha / merge_sha
# tree is mounted at /src on PYTHONPATH at runtime (byte-identical env across arms).
FROM python:3.12-slim
ENV PIP_NO_CACHE_DIR=1 PYTHONDONTWRITEBYTECODE=1 VLLM_TARGET_DEVICE=cpu
RUN pip install --index-url https://download.pytorch.org/whl/cpu torch \\
 && pip install {deps}
WORKDIR /bench
# run_workload.sh is bind-mounted and invoked by run.sh; no baked CMD.
"""

# ---- the GPU base image: build vLLM at base_sha so kernels/serving are real ----
GPU_DOCKERFILE = """# AUTO-GENERATED by gen_workloads.py — PR #{pr} ({title})
# Isolated GPU workload image. Builds on the official vLLM CUDA base so Triton
# kernels / serving paths are real. The arm's vllm/ tree is swapped in at runtime.
# ONLY builds on a CUDA host (run.sh skips this PR when no --gpus is available).
ARG CUDA_TAG=12.4.1-devel-ubuntu22.04
FROM nvidia/cuda:${{CUDA_TAG}}
ENV DEBIAN_FRONTEND=noninteractive PIP_NO_CACHE_DIR=1
RUN apt-get update && apt-get install -y python3 python3-pip git && rm -rf /var/lib/apt/lists/*
# vLLM + its CUDA wheels pinned at the PR's version; the mounted tree overrides vllm/.
RUN pip install vllm
WORKDIR /bench
"""

RUN_CPU = """#!/usr/bin/env bash
# AUTO-GENERATED — PR #{pr}. Mimic the author's workload for BOTH arms.
# Mounts: /src = the arm's vllm tree (base or gold). Prints parseable lines.
set -euo pipefail
ARM="${{ARM:-unknown}}"
echo "# pr={pr} arm=$ARM cmd={cmd!r}"
cd /src
export PYTHONPATH=/src:${{PYTHONPATH:-}}
{cmd}
"""

RUN_GPU = """#!/usr/bin/env bash
# AUTO-GENERATED — PR #{pr} (GPU). Author workload: {cmd!r}
# Requires CUDA + (maybe) a model mounted at /weights. run.sh only calls this
# when a GPU is present; otherwise the row stays reported-only/pending.
set -euo pipefail
ARM="${{ARM:-unknown}}"
if ! python3 -c "import torch;assert torch.cuda.is_available()" 2>/dev/null; then
  echo "# pr={pr} arm=$ARM SKIP=no_cuda — GPU workload, run on a CUDA box"
  exit 0
fi
echo "# pr={pr} arm=$ARM cmd={cmd!r}"
cd /src
export PYTHONPATH=/src:${{PYTHONPATH:-}}
{model_env}{cmd}
"""

DOWNLOAD_NONE = """#!/usr/bin/env bash
# AUTO-GENERATED — PR #{pr}. No model weights needed (cluster={cluster}).
set -euo pipefail
echo "# pr={pr}: no weights to download (cluster {cluster})."
exit 0
"""

DOWNLOAD_HF = """#!/usr/bin/env bash
# AUTO-GENERATED — PR #{pr}. Fetch-on-demand weights for cluster {cluster}.
# SAFE: nothing downloads unless you RUN this on the target box. Skips if cached.
# Shared cache: ../../../.weights/{cluster} (gitignored, reused across the cluster's PRs).
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
CACHE="$HERE/../../../.weights/{cluster}"
HF_ID="{hf_id}"
SIZE="{size}"
{gate}
if [ -d "$CACHE" ] && [ -n "$(ls -A "$CACHE" 2>/dev/null)" ]; then
  echo "# {cluster}: cache HIT at $CACHE — skip download."; exit 0
fi
mkdir -p "$CACHE"
echo "# {cluster}: downloading $HF_ID ($SIZE) -> $CACHE"
python3 - "$HF_ID" "$CACHE" <<'PY'
import sys
from huggingface_hub import snapshot_download
snapshot_download(repo_id=sys.argv[1], local_dir=sys.argv[2],
                  local_dir_use_symlinks=False, resume_download=True)
print("done")
PY
{dataset}
echo "# {cluster}: ready at $CACHE"
"""

GATE_MIXTRAL = (
    'if [ "${ALLOW_MIXTRAL:-0}" != "1" ]; then\n'
    '  echo "# mixtral REFUSED: ~90GB. Re-run with ALLOW_MIXTRAL=1 on a box that can hold it."; exit 0\n'
    "fi"
)


def dataset_fetch(c):
    if "dataset_url" not in c:
        return ""
    return (
        f'DS="$CACHE/{c["dataset"]}.json"\n'
        f'if [ ! -f "$DS" ]; then echo "# fetching dataset {c["dataset"]}"; '
        f'curl -fsSL "{c["dataset_url"]}" -o "$DS"; fi'
    )


def main():
    made = []
    for pr_s, cks in sorted(PR_CLUSTERS.items(), key=lambda kv: int(kv[0])):
        w = WORK.get(pr_s, {})
        title = (w.get("title") or "").replace('"', "'")
        cmd = w.get("cmd") or f"python3 tasks/pr_{pr_s}/bench.py"
        needs = w.get("needs", "cpu")
        # prefer a model cluster over the bare none_* cluster when the pr is in both
        model_cks = [c for c in cks if CLUSTERS["clusters"][c]["model"]]
        cluster = model_cks[0] if model_cks else cks[0]
        c = CLUSTERS["clusters"][cluster]

        wdir = os.path.join(HERE, "tasks", f"pr_{pr_s}", "workload")
        os.makedirs(wdir, exist_ok=True)

        # Dockerfile
        df = (GPU_DOCKERFILE if needs == "gpu" else CPU_DOCKERFILE).format(
            pr=pr_s, title=title, deps=CPU_DEPS)
        open(os.path.join(wdir, "Dockerfile"), "w").write(df)

        # run_workload.sh
        if needs == "gpu":
            model_env = ""
            if c["model"]:
                model_env = 'export VLLM_MODEL="/weights"  # mounted from .weights/%s\n' % cluster
            rw = RUN_GPU.format(pr=pr_s, cmd=cmd, model_env=model_env)
        else:
            rw = RUN_CPU.format(pr=pr_s, cmd=cmd)
        p = os.path.join(wdir, "run_workload.sh")
        open(p, "w").write(rw)
        chmod_x(p)

        # download.sh
        if not c["model"]:
            dl = DOWNLOAD_NONE.format(pr=pr_s, cluster=cluster)
        else:
            gate = GATE_MIXTRAL if c.get("gated") == "ALLOW_MIXTRAL" else ""
            dl = DOWNLOAD_HF.format(
                pr=pr_s, cluster=cluster, hf_id=c["hf_id"], size=c["size"],
                gate=gate, dataset=dataset_fetch(c))
        p = os.path.join(wdir, "download.sh")
        open(p, "w").write(dl)
        chmod_x(p)

        # meta.json — what run.sh needs to drive this task
        meta = {
            "pr": int(pr_s), "needs": needs, "cluster": cluster,
            "model": c["model"], "cmd": cmd,
            "workload_kind": w.get("workload_kind"),
            "all_clusters": cks,
        }
        json.dump(meta, open(os.path.join(wdir, "meta.json"), "w"), indent=1)
        made.append((pr_s, needs, cluster))

    print("generated %d workload dirs:" % len(made))
    for pr, needs, cl in made:
        print(f"  pr_{pr:<6} needs={needs:<3} cluster={cl}")


if __name__ == "__main__":
    main()
