def pick_cluster(pr):
    cks = PR_CLUSTERS.get(pr) or ["none_gpu"]
    model_cks = [c for c in cks if CLUSTERS["clusters"][c]["model"]]
    cluster = model_cks[0] if model_cks else cks[0]
    return cluster, CLUSTERS["clusters"][cluster]


def gen_dir(pr, hw):
    t = layout.apply_override(layout.load_task(pr), hw)
    cluster, c = pick_cluster(pr)
    wdir = layout.workload_dir(pr, hw)
    wdir_rel = layout.rel(wdir)
    write(os.path.join(wdir, "Dockerfile"), render_dockerfile(pr, t, hw))
    cmd = (t.get("workload") or {}).get("cmd")
    model_env = f'export VLLM_MODEL="/weights"  # mounted from .weights/{cluster}\n' if c["model"] else ""
    write(os.path.join(wdir, "run_workload.sh"), RUN_GPU.format(pr=pr, hw=hw, cmd=cmd, model_env=model_env), exe=True)
    if not c["model"]:
        dl = DOWNLOAD_NONE.format(pr=pr, cluster=cluster)
    else:
        dl = DOWNLOAD_HF.format(pr=pr, cluster=cluster, hf_id=c["hf_id"], size=c["size"],
                                gate=GATE_MIXTRAL if c.get("gated") == "ALLOW_MIXTRAL" else "", dataset=dataset_fetch(c))
    write(os.path.join(wdir, "download.sh"), dl, exe=True)
    wj = build_workload_json(pr, t, hw, cluster, c, wdir_rel)
    write(os.path.join(wdir, "workload.json"), json.dumps(wj, indent=1, ensure_ascii=False) + "\n")
    write(os.path.join(wdir, "WORKLOAD.md"), render_workload_md(wj))
    return cluster


def gen_pr(pr, hw):
    hws = [layout.DEFAULT_HW] + ([hw] if hw != layout.DEFAULT_HW else [])
    for h in hws:
        cluster = gen_dir(pr, h)
    write(layout.problem_md(pr), render_problem_md(pr, layout.load_task(pr)))
    return cluster, hws


def main():
    a = sys.argv[1:]
    prs = [int(x) for x in a if x.isdigit()] or layout.workload_prs()
    hw = a[a.index("--hw") + 1] if "--hw" in a else layout.hw_slug()
    made = []
    for pr in prs:
        if not layout.has_workload(layout.load_task(pr)):
            print(f"  pr_{pr}: no workload.cmd in task.json, skipped")
            continue
        cluster, hws = gen_pr(pr, hw)
        made.append((pr, cluster, hws))
    print(f"generated {len(made)} PRs (problem.md + workload/{{{','.join([layout.DEFAULT_HW, hw])}}}/):")
    for pr, cl, hws in made:
        print(f"  pr_{pr:<6} cluster={cl:<12} hw={','.join(hws)}")


if __name__ == "__main__":
    main()
