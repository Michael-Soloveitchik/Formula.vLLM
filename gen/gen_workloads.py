#!/usr/bin/env python3
"""Generate, from data/pr_<n>/task.json (+ clusters.json, solution.md, BASELINE_GAP.md, the runner),
everything a PR's experiment needs besides task.json itself:

  data/pr_<n>/problem.md                 the solver objective: issue + PR's solution (from solution.md)
                                         + the experiments / reported numbers (from task.json)
  data/pr_<n>/workload/default/          the generic definition
  data/pr_<n>/workload/<hw-slug>/        THIS machine's definition = task.json with
                                         task.json:hardware_overrides[<hw-slug>] applied
                                         (cmd, repeats, extra_pip, torch_fix, note)
  each workload dir holds:
    Dockerfile        rendered from templates/Dockerfile.gpu-wheel: the ONLY image run_one.sh builds
                      (wheel, shas, torch_fix, extra_pip baked in; `docker build -t vllm-task:<n> <dir>`)
    run_workload.sh   the workload cmd for one arm (ARM env), prints parseable lines, skips without CUDA
    download.sh       fetch-on-demand weights for the PR's cluster into .weights/<cluster>; never runs by itself
    workload.json     CANONICAL, self-contained description of the experiment: image, exact cmd + env,
                      measurement policy (read from pipeline/run_one.sh at generation time), metrics,
                      reported numbers + the author's hardware/args quoted from pr.md, requirements,
                      reproduced numbers (results.<hw>.json) and the BASELINE_GAP.md verdict
    WORKLOAD.md       the same rendered for humans: what is measured, how to re-run 1:1 without run_one.sh

    python3 gen/gen_workloads.py              # every PR with a workload
    python3 gen/gen_workloads.py --pr 37225   # one PR (run_one.sh does this before each build)
    python3 gen/gen_workloads.py --hw h100-80gb   # render for another slug (default: this machine's)

Re-runnable: overwrites the generated files, never touches task.json / bench.py / notes.md. Other
slugs' workload dirs are left alone. No timestamps: unchanged inputs = no diff.
"""
