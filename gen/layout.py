#!/usr/bin/env python3
"""layout.py — the ONE place that knows where a PR's files live. Every script imports it
(`from gen import layout`, after putting the repo root on sys.path); shell scripts call it
(`python3 gen/layout.py pr_dir 37225`) or source gen/layout.sh.

Repo root dirs: pipeline/ (run + measure + record), gen/ (generators, config, this file),
tools/ (lint, dashboard server), templates/ (Dockerfile templates), web/ (dashboard),
data/pr_<n>/ (everything about one PR), results/ (web aggregate only), .work/ (global scratch).

One directory per PR, data/pr_<n>/ (see README "Repository layout"):
  pr.md pr.diff solution.md        raw PR material (crawl)
  task.json                        the experiment definition (hand-written; `requirements` block generated)
  bench.py tests/ notes.md         hand-written per-task extras (optional)
  problem.md                       generated by gen_workloads.py (task.json + solution.md)
  workload/default/                generated by gen_workloads.py from task.json
  workload/<hw-slug>/              same, with task.json:hardware_overrides[<hw-slug>] applied
  results.<hw-slug>.json           written by record.py (via aggregate.py --write)
  logs/<hw-slug>/                  per-arm logs copied by record.py (git-ignored)
  work/                            build / scratch dir of run_one.sh (git-ignored)

Hardware slug: machine.py slug() (HW_SLUG env overrides), e.g. rtx5070ti, h100-80gb, cpu.

CLI (prints one line, for bash):
  python3 gen/layout.py <fn> [args...]            e.g. pr_dir 37225 | results_json 37225 [hw] | hw_slug
  python3 gen/layout.py task_get <pr> <dotted.key> [hw]   value from the hw-resolved task.json
                                                           (lists are space-joined, missing -> empty)
  python3 gen/layout.py env <pr> [hw]             `export K=V` lines for eval (layout.sh:layout_env)
"""
import glob
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if ROOT not in sys.path:
    sys.path.insert(0, ROOT)
DATA = os.path.join(ROOT, "data")
AGG = os.path.join(ROOT, "results")        # aggregate ONLY: all.json + manifest.json (+ .lock)
WORK_ROOT = os.path.join(ROOT, ".work")    # global scratch: run.lock, vllm_releases.json
TEMPLATES = os.path.join(ROOT, "templates")
DEFAULT_HW = "default"
_HW = None


# ---- hardware slug -----------------------------------------------------------------
def hw_slug():
    """slug of THIS machine (cached): HW_SLUG env, else machine.slug()."""
    global _HW
    if _HW is None:
        from pipeline import machine
        _HW = machine.slug()
    return _HW


def _hw(hw):
    return hw_slug() if hw in (None, "") else hw


# ---- per-PR paths --------------------------------------------------------------------
def pr_dir(pr):
    return os.path.join(DATA, f"pr_{int(pr)}")


def task_json(pr):
    return os.path.join(pr_dir(pr), "task.json")


def raw_md(pr):
    return os.path.join(pr_dir(pr), "pr.md")


def raw_diff(pr):
    return os.path.join(pr_dir(pr), "pr.diff")


def solution_md(pr):
    return os.path.join(pr_dir(pr), "solution.md")


def problem_md(pr):
    return os.path.join(pr_dir(pr), "problem.md")


def bench_py(pr):
    return os.path.join(pr_dir(pr), "bench.py")


def notes_md(pr):
    return os.path.join(pr_dir(pr), "notes.md")


def tests_dir(pr):
    return os.path.join(pr_dir(pr), "tests")


def workload_dir(pr, hw=None):
    """data/pr_<n>/workload/<hw>  (hw None -> this machine's slug; pass 'default' explicitly)."""
    return os.path.join(pr_dir(pr), "workload", _hw(hw))


def workload_dir_for_run(pr, hw=None):
    """the workload dir run_one.sh builds from: this machine's slug if generated, else default."""
    d = workload_dir(pr, hw)
    return d if os.path.isdir(d) else workload_dir(pr, DEFAULT_HW)


def workload_hws(pr):
    """slugs that have a generated workload dir (default first)."""
    wroot = os.path.join(pr_dir(pr), "workload")
    if not os.path.isdir(wroot):
        return []
    hws = sorted(d for d in os.listdir(wroot) if os.path.isdir(os.path.join(wroot, d)))
    return ([DEFAULT_HW] if DEFAULT_HW in hws else []) + [h for h in hws if h != DEFAULT_HW]


def results_json(pr, hw=None):
    return os.path.join(pr_dir(pr), f"results.{_hw(hw)}.json")


def results_files(pr):
    """{hw_slug: path} of every results file this PR has (any machine)."""
    out = {}
    for f in sorted(glob.glob(os.path.join(pr_dir(pr), "results.*.json"))):
        m = re.fullmatch(r"results\.([a-z0-9-]+)\.json", os.path.basename(f))
        if m:
            out[m.group(1)] = f
    return out


def results_ai_files(pr):
    """{arm: path} of every results.ai.<arm>.json this PR has (CPU re-solve of a solver arm)."""
    out = {}
    for f in sorted(glob.glob(os.path.join(pr_dir(pr), "results.ai.*.json"))):
        m = re.fullmatch(r"results\.ai\.([a-z0-9-]+)\.json", os.path.basename(f))
        if m:
            out[m.group(1)] = f
    return out


def results_json_any(pr, hw=None):
    """this machine's results file if present, else the first available slug's (or None)."""
    p = results_json(pr, hw)
    if os.path.exists(p):
        return p
    fs = results_files(pr)
    return next(iter(fs.values()), None)


def all_results_files():
    """[(pr, hw_slug, path)] over every PR dir, sorted."""
    out = []
    for pr in prs():
        for hw, p in results_files(pr).items():
            out.append((pr, hw, p))
    return out


def logs_dir(pr, hw=None):
    return os.path.join(pr_dir(pr), "logs", _hw(hw))


def work_dir(pr):
    return os.path.join(pr_dir(pr), "work")


def work_file(pr, name):
    return os.path.join(work_dir(pr), name)


# ---- global paths --------------------------------------------------------------------
def index_json():
    return os.path.join(ROOT, "index.json")


def clusters_json():
    return os.path.join(ROOT, "clusters.json")


def all_json():
    return os.path.join(AGG, "all.json")


def manifest_json():
    return os.path.join(AGG, "manifest.json")


def agg_lock():
    return os.path.join(AGG, ".lock")


def run_lock():
    return os.path.join(WORK_ROOT, "run.lock")


def releases_json():
    return os.path.join(WORK_ROOT, "vllm_releases.json")


def template(name):
    return os.path.join(TEMPLATES, name)


def rel(path):
    return os.path.relpath(path, ROOT)


# ---- task.json ---------------------------------------------------------------------
def prs():
    """every PR that has a data/pr_<n>/ dir, ascending."""
    out = []
    if os.path.isdir(DATA):
        for d in os.listdir(DATA):
            m = re.fullmatch(r"pr_(\d+)", d)
            if m and os.path.isdir(os.path.join(DATA, d)):
                out.append(int(m.group(1)))
    return sorted(out)


def load_task(pr):
    """the raw task.json (no hardware override applied); {} when missing."""
    try:
        return json.load(open(task_json(pr)))
    except Exception:
        return {}


def save_task(pr, d):
    """write task.json only if its content changed (keeps regenerations diff-free)."""
    p = task_json(pr)
    txt = json.dumps(d, indent=1, ensure_ascii=False) + "\n"
    try:
        if open(p).read() == txt:
            return False
    except Exception:
        pass
    os.makedirs(os.path.dirname(p), exist_ok=True)
    tmp = p + ".tmp"
    open(tmp, "w").write(txt)
    os.replace(tmp, p)
    return True


OVERRIDE_KEYS = ("cmd", "repeats", "extra_pip", "torch_fix", "note")


def apply_override(task, hw):
    """task.json with hardware_overrides[hw] folded in: cmd/note -> workload.cmd/workload.note,
    repeats/extra_pip/torch_fix -> top level. Adds `hw` (the slug the result is for) and
    `hw_override` (the applied block, or null)."""
    t = json.loads(json.dumps(task))
    ov = ((t.get("hardware_overrides") or {}).get(hw)) if hw and hw != DEFAULT_HW else None
    if ov:
        wl = t.setdefault("workload", {})
        for k, v in ov.items():
            if k == "cmd":
                wl["cmd"] = v
            elif k == "note":
                wl["note"] = (wl.get("note") or "")
                wl["note"] = (wl["note"] + " " if wl["note"] else "") + f"[{hw}] {v}"
            else:
                t[k] = v
    t["hw"] = hw or DEFAULT_HW
    t["hw_override"] = ov or None
    return t


def resolve_task(pr, hw=None):
    """task.json as THIS machine (or `hw`) runs it."""
    return apply_override(load_task(pr), _hw(hw))


def has_workload(task):
    return bool((task.get("workload") or {}).get("cmd"))


def workload_prs():
    """PRs whose task.json defines a workload cmd (the reproducible set), in PR order."""
    return [pr for pr in prs() if has_workload(load_task(pr))]


def task_get(pr, key, hw=None):
    """dotted lookup in the hw-resolved task.json; '' when missing."""
    v = resolve_task(pr, hw)
    for k in key.split("."):
        v = v.get(k, "") if isinstance(v, dict) else ""
    return v


# ---- CLI -----------------------------------------------------------------------------
def _fmt(v):
    if isinstance(v, list):
        return " ".join(str(x) for x in v)
    if isinstance(v, bool):
        return "1" if v else "0"
    return "" if v is None else str(v)


def _env(pr, hw=None):
    hw = _hw(hw)
    kv = {
        "PR_DIR": pr_dir(pr), "TASK_JSON": task_json(pr), "PROBLEM_MD": problem_md(pr),
        "WORK_DIR": work_dir(pr), "RESULTS_JSON": results_json(pr, hw), "LOGS_DIR": logs_dir(pr, hw),
        "WORKLOAD_DIR": workload_dir_for_run(pr, hw), "WORKLOAD_DEFAULT_DIR": workload_dir(pr, DEFAULT_HW),
        "HW_SLUG": hw, "WORK_ROOT": WORK_ROOT, "RUN_LOCK": run_lock(), "AGG_DIR": AGG,
    }
    return "\n".join(f"export {k}={_sh(v)}" for k, v in kv.items())


def _sh(v):
    return "'" + str(v).replace("'", "'\\''") + "'"


def main(argv):
    if len(argv) < 2 or argv[1] in ("-h", "--help"):
        print(__doc__)
        return 0
    fn, args = argv[1], argv[2:]
    if fn == "env":
        print(_env(int(args[0]), args[1] if len(args) > 1 else None))
        return 0
    if fn == "task_get":
        print(_fmt(task_get(int(args[0]), args[1], args[2] if len(args) > 2 else None)))
        return 0
    f = globals().get(fn)
    if not callable(f) or fn.startswith("_"):
        sys.exit(f"layout.py: unknown function {fn!r}")
    conv = [int(a) if a.isdigit() else a for a in args]
    v = f(*conv)
    print(_fmt(v) if not isinstance(v, (dict, tuple)) else json.dumps(v))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
