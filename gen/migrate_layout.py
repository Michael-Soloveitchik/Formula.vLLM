#!/usr/bin/env python3
"""Migrate the repo to ONE directory per PR (data/pr_<n>/). Idempotent: re-running on a
migrated tree is a no-op; a tree that is half old / half new (e.g. main after a merge, with
fresh results/<pr>.json and .work/pr_<n>/ written by a queue that was still running) is
finished off. Tracked files move with `git mv`, scratch with os.rename. Writes MIGRATION.md
(root) whenever something was moved / merged / dropped.

    python3 gen/migrate_layout.py            # do it
    python3 gen/migrate_layout.py --dry-run  # only print what would happen

Old -> new (see README "Repository layout" for the owner of every file):
  data/prs/<field>/<area>/<pr>.md|.diff|.solution.md -> data/pr_<n>/pr.md|pr.diff|solution.md
  tasks/pr_<n>/metadata.json + workloads.json[pr] + index.json[pr] + data/area.json[pr]
      + reported-only scaffold results/<pr>.json:experiments -> data/pr_<n>/task.json
  tasks/pr_<n>/bench.py, tests/ -> data/pr_<n>/        RESULTS.md -> notes.md
  tasks/pr_<n>/problem.md, workload/   -> dropped (regenerated by gen/gen_workloads.py)
  tasks/pr_<n>/results_measured.json, results_blockpool.json -> dropped (superseded, summarised in notes.md)
  results/<pr>.json (real run)   -> data/pr_<n>/results.<hw-slug>.json (+ "hw_slug")
  results/<pr>.json (scaffold)   -> merged into task.json:experiments, file dropped
  .work/pr_<n>/ -> data/pr_<n>/work/ ; .work/<kind>_<pr>.<ext> -> data/pr_<n>/work/<kind>.<ext>
  logs/pr_<n>/* -> data/pr_<n>/logs/<hw-slug>/
  workloads.json, data/area.json -> dropped (task.json / index.json own those facts)
"""
import glob
import json
import os
import re
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from gen import layout  # noqa: E402

DRY = "--dry-run" in sys.argv
LOG = {"moved": [], "merged": [], "dropped": [], "written": [], "notes": []}
SCAFFOLD_TS = "2026-11-07"      # results with ts before this were hand-entered reported-only rows, never runs

# task.json key order (documented in README)
TASK_KEYS = ["pr", "title", "url", "date", "field", "area", "hardware", "base_sha", "merge_sha", "source_path",
             "reported_gain", "gain_kind", "gain_evidence",
             "source_files", "test_files", "wheel", "wheel_note", "torch_fix", "extra_pip", "extra_pip_note",
             "swap", "swap_note", "repeats", "test_note",
             "workload", "experiments", "experiments_note", "hardware_overrides", "requirements"]
META_DROP = {"perf_gain", "needs", "generated_by", "pr", "title", "field", "date", "hardware", "url", "base_sha", "merge_sha"}


def J(p):
    try:
        return json.load(open(p))
    except Exception:
        return None


def tracked(p):
    r = subprocess.run(["git", "ls-files", "--error-unmatch", os.path.relpath(p, ROOT)], cwd=ROOT,
                       capture_output=True, text=True)
    return r.returncode == 0


def mv(src, dst, why=""):
    if not os.path.exists(src):
        return False
    LOG["moved"].append((layout.rel(src), layout.rel(dst), why))
    if DRY:
        return True
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    if os.path.exists(dst):
        if os.path.isdir(src) and os.path.isdir(dst):
            for n in os.listdir(src):
                mv(os.path.join(src, n), os.path.join(dst, n), why)
            os.rmdir(src)
            return True
        LOG["notes"].append(f"{layout.rel(dst)} already exists; {layout.rel(src)} left in place")
        return False
    if tracked(src):
        subprocess.run(["git", "mv", "-k", os.path.relpath(src, ROOT), os.path.relpath(dst, ROOT)], cwd=ROOT, check=True)
        if os.path.exists(src):   # -k skipped (e.g. partly untracked dir): plain move
            shutil.move(src, dst)
    else:
        shutil.move(src, dst)
    return True


def rm(p, why):
    if not os.path.exists(p):
        return
    LOG["dropped"].append((layout.rel(p), why))
    if DRY:
        return
    if tracked(p):
        subprocess.run(["git", "rm", "-rq", "--cached", os.path.relpath(p, ROOT)], cwd=ROOT, check=True)
    if os.path.isdir(p):
        shutil.rmtree(p)
    else:
        os.remove(p)


def rmdir_empty(p):
    if os.path.isdir(p):
        for root, dirs, files in os.walk(p, topdown=False):
            for d in dirs:
                dp = os.path.join(root, d)
                if not os.listdir(dp):
                    os.rmdir(dp)
        if not os.listdir(p):
            os.rmdir(p)


# ---- catalog inputs ----------------------------------------------------------------
def area_map():
    a = J(os.path.join(layout.DATA, "area.json")) or {}
    out = {int(k): v for k, v in a.items()}
    if out:
        return out
    jl = os.path.join(layout.DATA, "index.jsonl")
    if os.path.exists(jl):
        for ln in open(jl):
            try:
                r = json.loads(ln)
            except ValueError:
                continue
            if r.get("pr") is not None:
                out[int(r["pr"])] = {"field": r.get("field"), "area": r.get("area")}
    return out


def old_raw(pr):
    """{suffix: path} of data/prs/<field>/<area>/<pr>.<suffix> still at the old place."""
    out = {}
    for root, dirs, files in os.walk(os.path.join(layout.DATA, "prs")):   # os.walk also enters dot-dirs (.buildkite)
        for f in files:
            if f.startswith(f"{pr}."):
                out[f[len(str(pr)):]] = os.path.join(root, f)
    return out


def compose_task(pr, idx, area, meta, wl, scaffold_exps, existing):
    """ONE task.json from every old owner of a fact. index.json wins for catalog facts,
    metadata.json for everything the runner reads, workloads.json only fills gaps."""
    t = dict(existing or {})
    t["pr"] = pr
    for k in ("title", "date", "field", "hardware", "base_sha", "merge_sha", "source_path",
              "reported_gain", "gain_kind", "gain_evidence"):
        if idx and k in idx:
            t[k] = idx[k]
    t["url"] = t.get("url") or f"https://github.com/vllm-project/vllm/pull/{pr}"
    if area and area.get("area"):
        t["area"] = area["area"]
    if meta:
        for k, v in meta.items():
            if k in META_DROP:
                continue
            t[k] = v
        wlm = dict(t.get("workload") or {})
        wlm.setdefault("needs", meta.get("needs") or (wl or {}).get("needs") or "gpu")
        if wl:
            wlm.setdefault("kind", wl.get("workload_kind"))
            wlm.setdefault("script", wl.get("script"))
            if not wlm.get("note") and wl.get("notes"):
                wlm["note"] = wl["notes"]
        t["workload"] = wlm
    elif wl and not t.get("workload"):
        exps = wl.get("experiments") or []
        t["workload"] = {"kind": wl.get("workload_kind"), "script": wl.get("script"), "cmd": wl.get("cmd"),
                         "unit": exps[0].get("unit") if exps else None, "needs": wl.get("needs", "gpu"),
                         "note": wl.get("notes")}
        t["experiments"] = [{k: e[k] for k in ("name", "unit", "parse", "reported") if k in e} for e in exps]
    # enrich experiments (unit / parse hint) from workloads.json by name
    if wl and t.get("experiments"):
        by = {e["name"]: e for e in wl.get("experiments") or []}
        for e in t["experiments"]:
            w = by.get(e["name"])
            if w:
                for k in ("unit", "parse"):
                    if not e.get(k) and w.get(k):
                        e[k] = w[k]
    # reported-only scaffold rows (scope / comparability notes) -> experiments
    if scaffold_exps:
        exps = t.setdefault("experiments", [])
        by = {e["name"]: e for e in exps}
        for s in scaffold_exps:
            s = {k: v for k, v in s.items() if k not in ("arms", "derived")}
            e = by.get(s["name"])
            if e is None:
                exps.append(s)
                by[s["name"]] = s
            else:
                for k, v in s.items():
                    if k == "reported" and isinstance(v, dict):
                        rep = e.setdefault("reported", {})
                        for rk, rv in v.items():
                            if rk not in rep or rep[rk] is None:
                                rep[rk] = rv
                    elif k not in e or e[k] in (None, ""):
                        e[k] = v
    if idx and idx.get("requirements") and not t.get("requirements"):
        t["requirements"] = idx["requirements"]
    t.setdefault("hardware_overrides", {})
    out = {k: t[k] for k in TASK_KEYS if k in t}
    out.update({k: v for k, v in t.items() if k not in out})
    return out


def real_result_slug(d):
    name = ((d.get("machine") or {}).get("gpu") or {}).get("name")
    from pipeline import machine
    return machine.slug_from_name(name) if name else layout.hw_slug()


def migrate_pr(pr, idx, areas, W):
    d = layout.pr_dir(pr)
    tdir = os.path.join(ROOT, "tasks", f"pr_{pr}")
    # 1. raw PR material
    raw = old_raw(pr)
    for suf, dst in ((".md", layout.raw_md(pr)), (".diff", layout.raw_diff(pr)), (".solution.md", layout.solution_md(pr))):
        if suf in raw:
            mv(raw[suf], dst, "raw PR material")
    # 2. task.json inputs
    meta = J(os.path.join(tdir, "metadata.json"))
    old_res = os.path.join(ROOT, "results", f"{pr}.json")
    res = J(old_res)
    scaffold = res if res is not None and (res.get("ts") or "") < SCAFFOLD_TS else None
    existing = layout.load_task(pr)
    if idx or meta or W.get(str(pr)) or scaffold or not existing:
        t = compose_task(pr, idx, areas.get(pr), meta, W.get(str(pr)), (scaffold or {}).get("experiments"), existing)
        if not DRY and layout.save_task(pr, t):
            LOG["written"].append(layout.rel(layout.task_json(pr)))
        if meta:
            LOG["merged"].append((f"tasks/pr_{pr}/metadata.json", "task.json"))
        if W.get(str(pr)):
            LOG["merged"].append((f"workloads.json[{pr}]", "task.json"))
        if scaffold:
            LOG["merged"].append((f"results/{pr}.json (reported-only scaffold, ts {scaffold.get('ts')})", "task.json:experiments"))
    # 3. hand-written task extras
    mv(os.path.join(tdir, "bench.py"), layout.bench_py(pr), "hand-written bench")
    mv(os.path.join(tdir, "tests"), layout.tests_dir(pr), "hand-written tests")
    mv(os.path.join(tdir, "RESULTS.md"), layout.notes_md(pr), "hand-written notes (old measured report)")
    rm(os.path.join(tdir, "metadata.json"), "merged into task.json")
    rm(os.path.join(tdir, "problem.md"), "regenerated by gen/gen_workloads.py from task.json + solution.md")
    rm(os.path.join(tdir, "workload"), "regenerated by gen/gen_workloads.py (meta.json dropped: duplicated task.json)")
    rm(os.path.join(tdir, "results_measured.json"), "pre-pipeline measurement (other host); superseded by results.<hw>.json, summarised in notes.md")
    rm(os.path.join(tdir, "results_blockpool.json"), "pre-pipeline measurement (other host); summarised in notes.md")
    for left in glob.glob(os.path.join(tdir, "*")):
        mv(left, os.path.join(d, os.path.basename(left)), "unclassified task file")
    rmdir_empty(tdir)
    # 4. results
    if res is not None:
        if scaffold:
            rm(old_res, "reported-only scaffold (never a run): its experiments live in task.json")
        else:
            slug = real_result_slug(res)
            dst = layout.results_json(pr, slug)
            if mv(old_res, dst, f"measured run -> hw slug {slug}") and not DRY:
                res["hw_slug"] = slug
                json.dump(res, open(dst, "w"), indent=1)
    # 5. scratch + logs
    mv(os.path.join(layout.WORK_ROOT, f"pr_{pr}"), layout.work_dir(pr), "scratch")
    for p in glob.glob(os.path.join(layout.WORK_ROOT, f"*_{pr}.*")):
        m = re.fullmatch(r"([a-z]+)_\d+(\..+)", os.path.basename(p))
        if m:
            mv(p, layout.work_file(pr, m.group(1) + m.group(2)), "scratch")
    ol = os.path.join(ROOT, "logs", f"pr_{pr}")
    if os.path.isdir(ol):
        mv(ol, layout.logs_dir(pr), "logs")


def write_migration_md():
    L = ["# Layout migration — what moved where, and why", "",
         "Written by `gen/migrate_layout.py` (re-run it any time; it only finishes what is left).",
         "The target layout and the owner of every file is the first section of README.md.", ""]
    L += ["## Single owner per fact", "",
          "| fact | was in | now ONLY in |", "|---|---|---|",
          "| title, date, field, area, hardware, shas, reported gain | index.json + tasks/pr_<n>/metadata.json + workloads.json + data/area.json | `data/pr_<n>/task.json` (index.json is generated from it) |",
          "| wheel, torch_fix, extra_pip, swap, source_files, test_files, repeats, test_note | metadata.json | `task.json` |",
          "| workload cmd / kind / script / unit / headline / note | metadata.json:workload + workloads.json + index.json:workload | `task.json:workload` (the cmd run_one.sh really runs; the workloads.json spelling was dropped) |",
          "| experiments + reported numbers + scope / comparability notes | metadata.json + workloads.json + reported-only scaffold results/<pr>.json | `task.json:experiments` |",
          "| machine requirements | index.json:requirements | `task.json:requirements` (generated by gen/gen_requirements.py) |",
          "| cluster / model / weights | clusters.json (+ copy in workload/meta.json) | `clusters.json` only; workload/meta.json dropped |",
          "| Dockerfile recipe | Dockerfile.gpu-wheel at root + inline string in gen_workloads.py | `templates/Dockerfile.gpu-wheel` (per-PR copies generated) |",
          "| reproduced numbers | results/<pr>.json | `data/pr_<n>/results.<hw-slug>.json` (results/all.json + manifest.json are regenerated aggregates) |",
          "| per-run logs | .work/pr_<n>/*.log (wiped by the next run) | `data/pr_<n>/logs/<hw-slug>/` (copied by record.py) |",
          "| problem statement for solvers | hand-written tasks/pr_<n>/problem.md (repeated solution.md + the reported numbers) | generated `data/pr_<n>/problem.md` from task.json + solution.md |",
          ""]
    L += ["## Dropped", "",
          "- `workloads.json`, `data/area.json`, `gen_area.py`: every fact now in task.json / index.json; the web reads `data/pr_<n>/pr.md` directly.",
          "- `tasks/pr_<n>/problem.md` (11 hand-written): regenerated; the issue paragraph came from solution.md's `## Problem` / `## Mechanism with the issue`.",
          "- `tasks/pr_<n>/workload/` incl. `meta.json`: regenerated per hardware slug.",
          "- `tasks/pr_21222/results_measured.json`, `results_blockpool.json`: measured on another host before this pipeline existed; the table in `data/pr_21222/notes.md` (was RESULTS.md) keeps the numbers.",
          "- reported-only scaffold `results/<pr>.json` (ts before 2026-11-07, 26 files): never runs; their experiments (reported numbers, scope notes) moved into task.json, their fake PASS/PASS arms were dropped.",
          "- `Dockerfile.gpu-wheel` (root): the template is `templates/Dockerfile.gpu-wheel`. `Dockerfile.gpu` (source build) and `Dockerfile.cpu-bench` are kept under templates/ as legacy references; nothing builds them.",
          "- `fetch_sources.sh` + the source-build mode of run_one.sh: every task is wheel-mode (the image clones the PR's commits itself).",
          "- scaffold results' top-level `environment` string (\"reported-only ... pending\"): a status, not a fact.",
          ""]
    # runs accumulate: keep every earlier "## Run" section, append this one
    p = os.path.join(ROOT, "MIGRATION.md")
    old = open(p).read() if os.path.exists(p) else ""
    runs = old.split("\n## Run ")[1:]
    R = [f"## Run {len(runs) + 1}", "",
         f"- moved: {len(LOG['moved'])} · merged: {len(LOG['merged'])} · dropped: {len(LOG['dropped'])} · task.json written: {len(LOG['written'])}"]
    for n in LOG["notes"]:
        R.append(f"- note: {n}")
    R += ["", "<details><summary>moves</summary>", ""]
    R += [f"- `{s}` -> `{d}` ({w})" for s, d, w in LOG["moved"]]
    R += ["", "</details>", "", "<details><summary>drops</summary>", ""]
    R += [f"- `{q}`: {w}" for q, w in LOG["dropped"]]
    R += ["", "</details>", ""]
    body = "\n".join(L) + "".join("\n## Run " + r for r in runs) + "\n" + "\n".join(R)
    open(p, "w").write(body)


def main():
    idx_list = J(layout.index_json()) or []
    IDX = {int(x["pr"]): x for x in idx_list}
    W = J(os.path.join(ROOT, "workloads.json")) or {}
    areas = area_map()
    prs = sorted(set(IDX) | set(layout.prs()) | {int(k) for k in W})
    for m in glob.glob(os.path.join(ROOT, "tasks", "pr_*")):
        prs.append(int(m.rsplit("_", 1)[1]))
    for m in glob.glob(os.path.join(ROOT, "results", "[0-9]*.json")):
        prs.append(int(os.path.basename(m)[:-5]))
    for pr in sorted(set(prs)):
        migrate_pr(pr, IDX.get(pr), areas, W)
    rm(os.path.join(ROOT, "workloads.json"), "merged into data/pr_<n>/task.json")
    rm(os.path.join(layout.DATA, "area.json"), "field/area live in task.json / index.json")
    for leftover in ("tasks", os.path.join("data", "prs"), "logs"):
        rmdir_empty(os.path.join(ROOT, leftover))
    n = sum(len(v) for k, v in LOG.items() if k != "notes")
    if n and not DRY:
        write_migration_md()
    print(f"{'DRY ' if DRY else ''}migrated: moved {len(LOG['moved'])}, merged {len(LOG['merged'])}, "
          f"dropped {len(LOG['dropped'])}, task.json written {len(LOG['written'])}" + ("" if n else " (nothing to do)"))
    for note in LOG["notes"]:
        print("  note:", note)


if __name__ == "__main__":
    main()
