#!/usr/bin/env python3
"""Apply AI-generated solutions and re-measure them with the SAME instrument as a run.

An AI solution for PR <n> lives under:

    data/pr_<n>/files/<arm>/            a mirror of the vLLM tree; every file here
                                        is OVERLAID on the baseline (base_sha) tree
                                        to form that arm. e.g.
    data/pr_<n>/files/claude/vllm/v1/spec_decode/ngram_proposer.py

This is exactly the layout run.sh's GPU box can `cp -a files/<arm>/. <vllm_site>/`
to apply the edit; nothing else is needed to reproduce it there.

For each requested PR and arm this script:
  1. builds the PR's CPU image (templates/Dockerfile.cpu-wheel copy) if absent,
  2. exports /base and /gold trees from the image (cached in data/pr_<n>/work),
  3. makes the arm tree  = base_full + files/<arm>/ overlay,
  4. runs data/pr_<n>/bench.py on the arm tree and the PR's-solution tree, ABBA-interleaved,
     REPEATS times, writing wl_<arm>_<i>.log / wl_gold_<i>.log — the identical log
     names pipeline/parse_workload.py already parses,
  5. folds the logs with parse_workload.py (SAME instrument as record.py) and
     writes data/pr_<n>/results.ai.<arm>.json  { scenario: {"gold", "<arm>", ratio} }.

CPU-only, no GPU, no vllm wheel: the arm's vllm/ tree runs on PYTHONPATH (the CPU
image mirrors the GPU one). The absolute speed is not the GPU number; this proves
the saved solution is correct + applies cleanly + the instrument reads it.

    python3 pipeline/apply_ai_solutions.py <pr> [<pr> ...] [--arm claude] [--repeats 5]
"""
from __future__ import annotations

import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, ROOT)
from gen import layout  # noqa: E402

ENGINE = os.environ.get("ENGINE", "docker")
REPEATS = int(os.environ.get("REPEATS", "5"))


def sh(cmd, **kw):
    return subprocess.run(cmd, shell=True, text=True, **kw)


def files_root(pr):
    return os.path.join(layout.pr_dir(pr), "files")


def arms_for(pr):
    root = files_root(pr)
    if not os.path.isdir(root):
        return []
    return sorted(d for d in os.listdir(root) if os.path.isdir(os.path.join(root, d)))


def cpu_dockerfile(pr):
    """the cpu workload dir's Dockerfile (generated by gen_workloads.py for the cpu slug)."""
    df = os.path.join(layout.pr_dir(pr), "workload", "cpu", "Dockerfile")
    return df if os.path.isfile(df) else None


def ensure_image(pr):
    img = f"vllm-task-cpu:{pr}"
    have = sh(f"{ENGINE} image inspect {img}", capture_output=True).returncode == 0
    if have:
        return img
    df = cpu_dockerfile(pr)
    if not df:
        die(f"no CPU Dockerfile for pr {pr} — run: python3 gen/gen_workloads.py {pr} --hw cpu")
    ctx = os.path.dirname(df)
    print(f"  building {img} from {layout.rel(df)} ...")
    if sh(f"{ENGINE} build -t {img} {ctx}").returncode != 0:
        die(f"image build failed for pr {pr}")
    return img


def export_trees(pr, img, work):
    base_full = os.path.join(work, "base_full")
    gold_full = os.path.join(work, "gold_full")
    if os.path.isfile(os.path.join(base_full, ".sha")) and os.path.isfile(os.path.join(gold_full, ".sha")):
        return base_full, gold_full
    os.makedirs(base_full, exist_ok=True)
    os.makedirs(gold_full, exist_ok=True)
    cid = sh(f"{ENGINE} create {img}", capture_output=True).stdout.strip()
    sh(f"{ENGINE} cp {cid}:/base/. {base_full}/")
    sh(f"{ENGINE} cp {cid}:/gold/. {gold_full}/")
    sh(f"{ENGINE} rm {cid}", capture_output=True)
    return base_full, gold_full


def make_arm_tree(pr, arm, base_full, work):
    """base_full + files/<arm>/ overlay -> work/ai_<arm> (the applied solution tree)."""
    dst = os.path.join(work, f"ai_{arm}")
    sh(f"rm -rf {dst} && cp -a {base_full} {dst}")
    overlay = os.path.join(files_root(pr), arm)
    sh(f"cp -a {overlay}/. {dst}/")
    return dst


def run_bench(pr, img, arm, tree, i, work):
    """one docker run of bench.py on <tree> at /src; log = wl_<arm>_<i>.log (parse_workload reads this)."""
    task = layout.pr_dir(pr)
    log = os.path.join(work, f"wl_{arm}_{i}.log")
    prelude = "rm -rf /src && ln -sfn /arm /src; export PYTHONPATH=/src:$PYTHONPATH"
    wl_cmd = (layout.load_task(pr).get("workload") or {}).get("cmd") or "python3 /task/bench.py"
    cmd = (
        f'{ENGINE} run --rm -e ARM={arm} '
        f'-v "{tree}":/arm:ro -v "{task}":/task:ro '
        f'{img} -lc "{prelude}; {wl_cmd}"'
    )
    with open(log, "w") as fh:
        rc = sh(cmd, stdout=fh, stderr=subprocess.STDOUT).returncode
    if rc != 0:
        print(f"    {arm} run {i}: FAILED rc={rc} (see {layout.rel(log)})")
        os.remove(log)
        return False
    return True


def parse(work, arms):
    out = subprocess.run(
        [sys.executable, os.path.join(HERE, "parse_workload.py"), work, *arms],
        capture_output=True, text=True,
    )
    return json.loads(out.stdout) if out.stdout.strip() else {"scenarios": {}}


def apply_one(pr, arm):
    print(f"PR {pr} arm '{arm}':")
    img = ensure_image(pr)
    work = layout.work_dir(pr)
    os.makedirs(work, exist_ok=True)
    base_full, gold_full = export_trees(pr, img, work)
    arm_tree = make_arm_tree(pr, arm, base_full, work)

    # clear old logs for these two arms so parse sees only this run
    for f in os.listdir(work):
        if f.startswith((f"wl_{arm}_", "wl_gold_")) and f.endswith(".log"):
            os.remove(os.path.join(work, f))

    # ABBA interleave (arm, PR, PR, arm, ...) — same as run_one.sh run_workloads_abba
    for i in range(1, REPEATS + 1):
        order = (arm, "gold") if i % 2 else ("gold", arm)
        for a in order:
            tree = arm_tree if a == arm else gold_full
            run_bench(pr, img, a, tree, i, work)

    folded = parse(work, [arm, "gold"])
    res = {"schema": "ai_solution_v1", "pr": pr, "arm": arm, "repeats": REPEATS,
           "instrument": "pipeline/parse_workload.py", "note": "CPU re-measure; speed is not the GPU number",
           "scenarios": {}}
    for name, sc in folded.get("scenarios", {}).items():
        unit = sc.get("unit")
        g = sc.get("gold")
        mine = sc.get(arm)
        entry = {"unit": unit, "gold": g, arm: mine}
        if g and mine and mine.get("mean"):
            higher = bool(unit and unit.rstrip().endswith("/s"))
            # ratio > 1 means "arm is better than the PR's solution"
            entry["ratio_arm_over_gold"] = round(
                (mine["mean"] / g["mean"]) if higher else (g["mean"] / mine["mean"]), 4
            )
        res["scenarios"][name] = entry

    out_path = os.path.join(layout.pr_dir(pr), f"results.ai.{arm}.json")
    with open(out_path, "w") as fh:
        json.dump(res, fh, indent=1)
        fh.write("\n")
    print(f"  -> {layout.rel(out_path)}")
    for name, e in res["scenarios"].items():
        r = e.get("ratio_arm_over_gold")
        print(f"     {name} ({e['unit']}): arm={_m(e.get(arm))} PR={_m(e.get('gold'))}"
              + (f"  ratio arm/PR={r}x" if r else ""))
    return out_path


def _m(s):
    return f"{s['mean']}±{s['sd']}(n{s['n']})" if s else "—"


def die(msg):
    print("ERROR:", msg, file=sys.stderr)
    sys.exit(1)


def main():
    a = sys.argv[1:]
    prs = [int(x) for x in a if x.isdigit()]
    arm = a[a.index("--arm") + 1] if "--arm" in a else None
    if "--repeats" in a:
        global REPEATS
        REPEATS = int(a[a.index("--repeats") + 1])
    if not prs:
        die("usage: apply_ai_solutions.py <pr> [<pr> ...] [--arm <name>] [--repeats N]")
    for pr in prs:
        arms = [arm] if arm else arms_for(pr)
        if not arms:
            print(f"PR {pr}: no data/pr_{pr}/files/<arm>/ solutions to apply — skipped")
            continue
        for ar in arms:
            apply_one(pr, ar)


if __name__ == "__main__":
    main()
